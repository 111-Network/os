def run_vault(root: Path, meta_dir: Path, check_mode: bool, write: bool,
              today: date) -> list:
    findings: list = []
    platforms, tags_vocab, planned, header = load_meta(meta_dir)
    vault = load_vault(root, findings)
    for entry in vault.entries:
        check_fields(entry, vault, platforms, tags_vocab, findings)
        check_body(entry, vault, planned, findings)
        check_naming(entry, vault, findings)
        check_staleness(entry, today, findings)
    check_relations_graph(vault, findings)

    agents_md = root / "AGENTS.md"
    if agents_md.exists():
        tokens = TOKEN(agents_md.stat().st_size)
        if tokens > 400:
            findings.append(Finding("AGENTS.md", 0, "WARN",
                                    f"B09: knowledge/AGENTS.md ~{int(tokens)} tokens exceeds 400"))

    has_errors = any(f.level == "ERROR" for f in findings)
    check_generated_files(vault, header, check_mode, write and not has_errors, findings)
    deduped = {}
    for f in findings:
        deduped.setdefault(f.key(), f)
    return sorted(deduped.values(), key=lambda f: f.key())


def print_findings(findings: list) -> None:
    by_file: dict = {}
    for f in findings:
        by_file.setdefault(f.path, []).append(f)
    for path in sorted(by_file):
        print(f"\n{path}:")
        for f in by_file[path]:
            loc = f":{f.line}" if f.line else ""
            print(f"  {f.level}{loc}  {f.message}")
    errors = sum(1 for f in findings if f.level == "ERROR")
    warns = sum(1 for f in findings if f.level == "WARN")
    print(f"\n{errors} error(s), {warns} warning(s)")


def cmd_selftest(meta_dir: Path, today: date) -> int:
    fixture = meta_dir / "fixture"
    failures = []
    valid = fixture / "valid"
    findings = run_vault(valid, meta_dir, check_mode=False, write=False, today=today)
    errors = [f for f in findings if f.level == "ERROR"]
    if errors:
        failures.append(f"valid fixture produced {len(errors)} ERROR(s): "
                        + "; ".join(e.message for e in errors))
    # generation smoke: write into a temp copy, verify marker/tally/determinism.
    with tempfile.TemporaryDirectory() as td:
        shutil.copytree(valid, Path(td) / "v", dirs_exist_ok=True)
        tmp_root = Path(td) / "v"
        run_vault(tmp_root, meta_dir, check_mode=False, write=True, today=today)
        first = (tmp_root / "llms.txt").read_text(encoding="utf-8")
        run_vault(tmp_root, meta_dir, check_mode=False, write=True, today=today)
        second = (tmp_root / "llms.txt").read_text(encoding="utf-8")
        if MARKER not in first.split("\n")[:1]:
            failures.append("generated root index lacks the marker line")
        if not re.search(r"\d+ proven · \d+ testing · \d+ candidate", first):
            failures.append("generated root index lacks the status tally")
        if first != second:
            failures.append("generation is not deterministic (second run differed)")
    invalid = fixture / "invalid"
    findings = run_vault(invalid, meta_dir, check_mode=False, write=False, today=today)
    invalid_errors = [f for f in findings if f.level == "ERROR"]
    if len(invalid_errors) < 3:
        failures.append(f"invalid fixture produced only {len(invalid_errors)} ERROR(s), "
                        f"expected >= 3: "
                        + "; ".join(e.message for e in invalid_errors))
    if failures:
        print("SELFTEST FAILED:")
        for f in failures:
            print(f"  - {f}")
        return 1
    print("selftest ok — valid fixture clean, generation deterministic, invalid fixture rejected")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="knowledge vault validator + index generator")
    ap.add_argument("--check", action="store_true",
                    help="validate + fail if regeneration would diff (writes nothing)")
    ap.add_argument("--selftest", action="store_true",
                    help="run the golden-fixture suite and nothing else")
    args = ap.parse_args()

    meta_dir = Path(__file__).resolve().parent
    root = meta_dir.parent
    today = date.today()

    if args.selftest:
        return cmd_selftest(meta_dir, today)

    findings = run_vault(root, meta_dir, check_mode=args.check,
                         write=not args.check, today=today)
    print_findings(findings)
    return 1 if any(f.level == "ERROR" for f in findings) else 0


if __name__ == "__main__":
    sys.exit(main())
