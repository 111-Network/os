MARKER = "<!-- generated by knowledge/_meta/build.py — do not hand-edit -->"

# Category folders, in the fixed order used by the root index (§Layout).
FOLDER_CATEGORY = {
    "projects": "project",
    "devices": "device",
    "recipes": "recipe",
    "protocols": "protocol",
    "models": "model",
    "concepts": "concept",
}
CATEGORY_FOLDER = {v: k for k, v in FOLDER_CATEGORY.items()}

# §Frontmatter — the 12 possible fields; anything else is an error.
ALL_FIELDS = {
    "title", "category", "status", "summary", "tags", "aliases",
    "platforms", "upstream", "license", "last_verified", "sources",
    "relations",
}

STATUSES = {"candidate", "testing", "proven", "hold"}

# Per-category required fields (§Frontmatter matrix; schema.md §2).
REQUIRED_COMMON = {"title", "category", "summary", "tags"}
REQUIRED_BY_CATEGORY = {
    "project": {"status", "upstream", "license", "platforms", "last_verified"},
    "device": {"status", "platforms", "last_verified"},
    "recipe": {"status", "last_verified", "relations"},
    "protocol": {"status", "upstream", "last_verified"},
    "model": {"status", "license", "last_verified"},
    "concept": set(),
}
# Fields forbidden per category (schema.md §2 matrix — inapplicable fields are
# omitted, never present-but-empty; concepts are timeless: no lifecycle).
FORBIDDEN_BY_CATEGORY = {
    "concept": {"status", "last_verified", "platforms", "upstream", "license"},
    "recipe": {"platforms", "upstream", "license"},
    "protocol": {"platforms"},
}

# §Relations — controlled vocabulary with inverses (_meta/predicates.md).
INVERSE = {
    "implements": "implemented_by",
    "implemented_by": "implements",
    "runs_on": "hosted_by",
    "hosted_by": "runs_on",
    "depends_on": "required_by",
    "required_by": "depends_on",
    "used_in": "uses",
    "uses": "used_in",
    "supersedes": "superseded_by",
    "superseded_by": "supersedes",
}
SYMMETRIC = {"alternative_to", "relates_to"}  # one direction satisfies both
ALL_PREDICATES = set(INVERSE) | SYMMETRIC

# §File rules — fixed body sections, exact headings, fixed order.
SECTIONS = [
    "What it is", "Use when", "Do NOT use when", "Details", "Evidence", "Links",
]

# §Status lifecycle — Evidence subsections required per tier.
