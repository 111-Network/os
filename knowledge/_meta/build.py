EVIDENCE_BY_STATUS = {
    "candidate": ["Alternatives considered"],
    "testing": ["Alternatives considered", "Smoke test"],
    "proven": ["Alternatives considered", "Smoke test", "Field log"],
    "hold": ["Alternatives considered"],
}

# §Index contract — line grammar pieces.
TALLY_OVERRIDE = "full catalog under Optional — read it first"

# Shapes.
SLUG_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
WIKILINK_RE = re.compile(r"^\[\[([a-z0-9]+(-[a-z0-9]+)*)\]\]$")
SPDX_RE = re.compile(r"^[()A-Za-z0-9-.:+]+( (AND|OR|WITH) [()A-Za-z0-9-.:+]+)*$")
URL_RE = re.compile(r"^[a-z][a-z0-9+.-]*://[^/?#\s]+(/[^?#\s]*)?$")
KEY_RE = re.compile(r"^[a-z][a-z0-9_]*$")
DATE_RE = re.compile(r"\b(\d{4})-(\d{2})-(\d{2})\b")
PROSE_LINK_RE = re.compile(r"(!?)\[\[([^\[\]\n]+)\]\]")

# Token budgets are measured as chars/4 (§File rules) and are warning-only.
TOKEN = lambda chars: chars / 4  # noqa: E731 - spec formula, keep visible
BODY_TOKEN_CEILING = 1500
RECIPE_TOKEN_CEILING = 2500
BODY_TOKEN_FLOOR = 150
ROOT_INDEX_TOKEN_CEILING = 1500
ROOT_INDEX_LINE_CEILING = 60
CATEGORY_INDEX_TOKEN_CEILING = 1500
LONG_LINE = 120

# Staleness (single rule, §Status lifecycle).
STALE_WARN_DAYS = 90
STALE_ERROR_DAYS = 180  # on proven entries


# ---------------------------------------------------------------------------
# Findings and the entry model
# ---------------------------------------------------------------------------

@dataclass
class Finding:
    path: str       # vault-relative, forward slashes
    line: int       # 0 = file-level
    level: str      # "ERROR" | "WARN"
    message: str

    def key(self):
        return (self.path, self.line, self.level, self.message)


@dataclass
class Entry:
    path: Path                  # absolute
    rel: str                    # vault-relative
    folder: str                 # containing category folder
    slug: str                   # filename stem — the canonical ID
    fm: dict = field(default_factory=dict)          # parsed frontmatter
    body: str = ""                                   # text after closing ---
    category: str | None = None
    status: str | None = None
    title: str | None = None
    summary: str | None = None
    tags: list = field(default_factory=list)
    platforms: list = field(default_factory=list)
    relations: dict = field(default_factory=dict)    # predicate -> [slugs]
    last_verified: date | None = None

    @property
    def dated(self) -> bool:
        """Every file is timeless, dated, or a pointer; dated = carries
        last_verified. Undated entries are pointer/timeless and are exempt
        from the body floor (§File rules, derived mechanically)."""
        return self.last_verified is not None


@dataclass
class Vault:
    root: Path
    entries: list = field(default_factory=list)     # [Entry]
    slug_index: dict = field(default_factory=dict)  # slug -> Entry
    planned: set = field(default_factory=set)       # slugs from _meta/planned.md
    header: str | None = None                       # _meta/index-header.md


# ---------------------------------------------------------------------------
# Frontmatter parsing — strict YAML subset (§Frontmatter field hygiene)
# ---------------------------------------------------------------------------

def split_frontmatter(text: str):
    """Return (yaml_text, body_text) or (None, None) when no block exists."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None, None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return "\n".join(lines[1:i]), "\n".join(lines[i + 1:])
    return None, None  # unterminated block


def check_yaml_subset(fm_text: str, rel: str, findings: list) -> None:
    """Subset lint: no anchors/aliases, no merge keys, no multi-line scalars,
    scalars plain or double-quoted only (§Frontmatter)."""
    try:
        events = list(yaml.parse(fm_text, Loader=yaml.SafeLoader))
    except yaml.YAMLError:
        return  # parse errors are reported by the loader step
    for ev in events:
        line = getattr(ev, "start_mark", None)
        line = (line.line + 1) if line is not None else 0
        if isinstance(ev, AliasEvent):
            findings.append(Finding(rel, line, "ERROR",
                                    "YAML aliases are outside the frontmatter subset"))
        anchor = getattr(ev, "anchor", None)
        if anchor:
            findings.append(Finding(rel, line, "ERROR",
                                    f"YAML anchor '&{anchor}' is outside the frontmatter subset"))
        if isinstance(ev, ScalarEvent):
            if ev.style in ("|", ">"):
                findings.append(Finding(rel, line, "ERROR",
                                        "multi-line block scalars are outside the frontmatter subset"))
            elif ev.style == "'":
                findings.append(Finding(rel, line, "ERROR",
                                        "single-quoted scalars are outside the frontmatter subset "
                                        "(use plain or double-quoted)"))
            elif ev.start_mark and ev.end_mark and ev.end_mark.line > ev.start_mark.line:
                findings.append(Finding(rel, line, "ERROR",
                                        "multi-line scalars are outside the frontmatter subset"))


def load_frontmatter(entry: Entry, text: str, findings: list) -> None:
    rel = entry.rel
    fm_text, body = split_frontmatter(text)
    if fm_text is None:
        findings.append(Finding(rel, 1, "ERROR",
                                "missing YAML frontmatter block (file must start with '---')"))
        return
    check_yaml_subset(fm_text, rel, findings)
    try:
        fm = yaml.safe_load(fm_text)
    except yaml.YAMLError as exc:
        findings.append(Finding(rel, 1, "ERROR", f"frontmatter is not parseable YAML: {exc}"))
        return
    if fm is None:
        fm = {}
    if not isinstance(fm, dict):
        findings.append(Finding(rel, 1, "ERROR", "frontmatter must be one YAML mapping"))
        return
    entry.fm = fm
    entry.body = body


# ---------------------------------------------------------------------------
# Controlled lists, vault loading (schema.md §4 setup)
# ---------------------------------------------------------------------------

def read_list_section(path: Path, heading: str) -> set:
    """First token of each '- ' line under '## <heading>' (schema.md §4.4)."""
    out = set()
    if not path.exists():
        return out
    in_section = False
    for line in path.read_text(encoding="utf-8").split("\n"):
        if line.startswith("## "):
            in_section = line[3:].strip().lower() == heading.lower()
            continue
        if in_section and line.startswith("- "):
            token = line[2:].strip().split(" ")[0].strip()
            if token and not token.startswith("("):
                out.add(token)
    return out


def load_meta(meta_dir: Path):
    platforms = read_list_section(meta_dir / "vocabularies.md", "Platforms")
    tags = read_list_section(meta_dir / "vocabularies.md", "Tags")
    planned = read_list_section(meta_dir / "planned.md", "Registry")
    header_path = meta_dir / "index-header.md"
    header = header_path.read_text(encoding="utf-8").strip() if header_path.exists() else None
    return platforms, tags, planned, header


def load_vault(root: Path, findings: list) -> Vault:
    vault = Vault(root=root)
    for folder in FOLDER_CATEGORY:
        folder_path = root / folder
        if not folder_path.is_dir():
            continue
        for md in sorted(folder_path.glob("*.md")):
            entry = Entry(path=md, rel=f"{folder}/{md.name}", folder=folder,
                          slug=md.stem)
            load_frontmatter(entry, md.read_text(encoding="utf-8"), findings)
            vault.entries.append(entry)
            if entry.slug in vault.slug_index:
                findings.append(Finding(entry.rel, 0, "ERROR",
                                        f"N01: slug '{entry.slug}' is not vault-wide-unique"))
            vault.slug_index[entry.slug] = entry
    return vault


# ---------------------------------------------------------------------------
# Per-entry checks: fields, body, naming (schema.md §1 F/B/N rules)
# ---------------------------------------------------------------------------

def check_fields(entry: Entry, vault: Vault, platforms: set, tags_vocab: set,
                 findings: list) -> None:
    rel = entry.rel
    fm = entry.fm
    if not fm:
        return  # F01 already reported by load_frontmatter

    for key in fm:
        if key not in ALL_FIELDS:
            findings.append(Finding(rel, 0, "ERROR", f"F02: unknown field '{key}'"))
        elif not KEY_RE.match(key):
            findings.append(Finding(rel, 0, "ERROR",
                                    f"F02: field '{key}' is not lowercase snake_case"))
        value = fm[key]
        if value is None or value == "" or value == [] or value == {}:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"F04: field '{key}' is present but empty — omit it"))

    category = fm.get("category")
    if category not in set(FOLDER_CATEGORY.values()):
        findings.append(Finding(rel, 0, "ERROR",
                                f"F05: category '{category}' outside the enum"))
        category = None
    else:
        entry.category = category
        if FOLDER_CATEGORY.get(entry.folder) != category:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"F05: folder '{entry.folder}' does not match category '{category}'"))

    if category:
        required = REQUIRED_COMMON | REQUIRED_BY_CATEGORY.get(category, set())
        for f in sorted(required):
            if f not in fm:
                findings.append(Finding(rel, 0, "ERROR",
                                        f"F03: '{f}' is required for category '{category}'"))
        for f in sorted(FORBIDDEN_BY_CATEGORY.get(category, set())):
            if f in fm:
                findings.append(Finding(rel, 0, "ERROR",
                                        f"F04: '{f}' is forbidden for category '{category}'"))

    status = fm.get("status")
    if status is not None:
        if status not in STATUSES:
            findings.append(Finding(rel, 0, "ERROR", f"F06: status '{status}' invalid"))
        else:
            entry.status = status

    title = fm.get("title")
    if isinstance(title, str):
        entry.title = title
        if "|" in title or "\n" in title:
            findings.append(Finding(rel, 0, "ERROR", "F07: title contains '|' or newline"))
        if re.search(r"\band\b", title, re.IGNORECASE):
            findings.append(Finding(rel, 0, "WARN",
                                    "F08: title contains 'and' — consider splitting the entry"))

    summary = fm.get("summary")
    if isinstance(summary, str):
        entry.summary = summary
        words = summary.split()
        if not (1 <= len(words) <= 12) or "\n" in summary or "|" in summary:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"F09: summary must be 1-12 words, one line, no '|' "
                                    f"(got {len(words)} words)"))

    tags = fm.get("tags")
    if isinstance(tags, list):
        entry.tags = [t for t in tags if isinstance(t, str)]
        for t in entry.tags:
            if not re.match(r"^[a-z0-9][a-z0-9-]*$", t):
                findings.append(Finding(rel, 0, "ERROR",
                                        f"F10: tag '{t}' is not a lowercase slug token"))
            elif t not in tags_vocab:
                findings.append(Finding(rel, 0, "WARN",
                                        f"F11: tag '{t}' not in _meta/vocabularies.md — review"))
    elif "tags" in fm:
        findings.append(Finding(rel, 0, "ERROR", "F10: 'tags' must be a list"))

    plats = fm.get("platforms")
    if isinstance(plats, list):
        entry.platforms = [p for p in plats if isinstance(p, str)]
        for p in entry.platforms:
            if p not in platforms:
                findings.append(Finding(rel, 0, "ERROR",
                                        f"F12: platform '{p}' not in _meta/vocabularies.md"))
    elif "platforms" in fm:
        findings.append(Finding(rel, 0, "ERROR", "F12: 'platforms' must be a list"))

    license_ = fm.get("license")
    if license_ is not None and isinstance(license_, str):
        if not SPDX_RE.match(license_):
            findings.append(Finding(rel, 0, "ERROR",
                                    f"F14: license '{license_}' fails SPDX expression shape"))

    sources = fm.get("sources")
    if isinstance(sources, list):
        if len(sources) > 5:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"F15: {len(sources)} sources — at most 5"))
        for s in sources:
            if not isinstance(s, str) or not URL_RE.match(s):
                findings.append(Finding(rel, 0, "ERROR",
                                        f"F15: source '{s}' must be scheme+host+path only"))
    elif "sources" in fm:
        findings.append(Finding(rel, 0, "ERROR", "F15: 'sources' must be a list"))

    lv = fm.get("last_verified")
    if lv is not None:
        parsed = None
        if isinstance(lv, date):
            parsed = lv
        elif isinstance(lv, str):
            m = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", lv)
            if m:
                try:
                    parsed = date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
                except ValueError:
                    parsed = None
        if parsed is None:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"F16: last_verified '{lv}' is not an ISO 8601 date"))
        else:
            entry.last_verified = parsed

    relations = fm.get("relations")
    if isinstance(relations, dict):
        for pred, targets in relations.items():
            if not isinstance(targets, list):
                findings.append(Finding(rel, 0, "ERROR",
                                        f"R01: relation '{pred}' value must be a flow list"))
                continue
            cleaned = []
            for t in targets:
                if isinstance(t, list):
                    findings.append(Finding(rel, 0, "ERROR",
                                            f"R01: unquoted wikilink in '{pred}' parsed as a "
                                            f"nested list — double-quote all [[wikilinks]]"))
                    continue
                if not isinstance(t, str) or not WIKILINK_RE.match(t):
                    findings.append(Finding(rel, 0, "ERROR",
                                            f"R01: relation target '{t}' is not a quoted "
                                            f"bare [[slug]]"))
                    continue
                cleaned.append(WIKILINK_RE.match(t).group(1))
            entry.relations[pred] = cleaned
    elif "relations" in fm:
        findings.append(Finding(rel, 0, "ERROR", "R01: 'relations' must be one mapping level"))

    # F13 — platforms is shorthand; a platform token that is itself a device
    # slug must also be a runs_on edge.
    for p in entry.platforms:
        target = vault.slug_index.get(p)
        if target is not None and target.category == "device" \
                and p not in entry.relations.get("runs_on", []):
            findings.append(Finding(rel, 0, "WARN",
                                    f"F13: platform '{p}' is an existing device slug but "
                                    f"absent from runs_on"))


def check_body(entry: Entry, vault: Vault, planned: set, findings: list) -> None:
    rel, body = entry.rel, entry.body

    # B01 — first non-empty body line must equal the summary verbatim.
    first_line = next((ln for ln in body.split("\n") if ln.strip()), None)
    if entry.summary and first_line is not None and first_line.strip() != entry.summary.strip():
        findings.append(Finding(rel, 0, "ERROR",
                                "B01: first body line must equal frontmatter summary verbatim"))

    # B02 — fixed H2 sections, exact strings, fixed order, nothing else at H2.
    h2s = re.findall(r"^## (.+?)\s*$", body, re.MULTILINE)
    if h2s != SECTIONS:
        findings.append(Finding(rel, 0, "ERROR",
                                f"B02: H2 sections must be exactly {SECTIONS}, got {h2s}"))

    # B03/B04 — Evidence subsections per status tier.
    ev_match = re.search(r"^## Evidence\s*$", body, re.MULTILINE)
    evidence_text = ""
    if ev_match:
        rest = body[ev_match.end():]
        next_h2 = re.search(r"^## ", rest, re.MULTILINE)
        evidence_text = rest[:next_h2.start()] if next_h2 else rest
    subs = re.findall(r"^### (.+?)\s*$", evidence_text, re.MULTILINE)
    known_subs = ["Alternatives considered", "Smoke test", "Field log"]
    if entry.category == "concept":
        required_subs: list = []
    else:
        required_subs = EVIDENCE_BY_STATUS.get(entry.status or "candidate", [])
    for s in required_subs:
        if s not in subs:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"B03: '### {s}' required at status "
                                    f"'{entry.status or 'candidate'}'"))
    for s in subs:
        if s not in known_subs:
            findings.append(Finding(rel, 0, "WARN",
                                    f"B04: unknown Evidence subsection '{s}'"))
        elif s not in required_subs:
            findings.append(Finding(rel, 0, "WARN",
                                    f"B04: '### {s}' is above this entry's status tier"))

    # F17 — last_verified must equal the newest dated Evidence line.
    dated = [date(int(y), int(m), int(d))
             for y, m, d in DATE_RE.findall(evidence_text)
             if _valid_date(y, m, d)]
    if dated and entry.last_verified and max(dated) != entry.last_verified:
        findings.append(Finding(rel, 0, "ERROR",
                                f"F17: last_verified {entry.last_verified} != newest Evidence "
                                f"date {max(dated)}"))

    # B05 — long lines.
    for i, ln in enumerate(body.split("\n"), 1):
        if len(ln) > LONG_LINE:
            findings.append(Finding(rel, i, "WARN",
                                    f"B05: body line >{LONG_LINE} chars"))

    # B06–B08 — prose wikilinks (outside fenced code blocks).
    prose = re.sub(r"```.*?```", "", body, flags=re.DOTALL)
    for m in PROSE_LINK_RE.finditer(prose):
        bang, inner = m.group(1), m.group(2).strip()
        if bang or not re.match(r"^[a-z0-9]+(-[a-z0-9]+)*$", inner):
            findings.append(Finding(rel, 0, "ERROR",
                                    f"B06: wikilink '[[{inner}]]' is not a bare slug "
                                    f"(no pipes/aliases/headings/embeds)"))
            continue
        if inner in vault.slug_index:
            continue  # resolves
        normalized = re.sub(r"[_\s]+", "-", inner.lower())
        if normalized in vault.slug_index and normalized != inner:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"B08: '[[{inner}]]' — did you mean [[{normalized}]]?"))
        elif inner not in planned:
            findings.append(Finding(rel, 0, "WARN",
                                    f"B07: dangling prose wikilink '[[{inner}]]' not "
                                    f"registered in _meta/planned.md"))

    # B09 — token budgets (chars/4, frontmatter excluded, warning-only).
    tokens = TOKEN(len(body))
    ceiling = RECIPE_TOKEN_CEILING if entry.category == "recipe" else BODY_TOKEN_CEILING
    if tokens > ceiling:
        findings.append(Finding(rel, 0, "WARN",
                                f"B09: body ~{int(tokens)} tokens exceeds {ceiling}"))
    if entry.dated and tokens < BODY_TOKEN_FLOOR:
        findings.append(Finding(rel, 0, "WARN",
                                f"B09: body ~{int(tokens)} tokens under the {BODY_TOKEN_FLOOR} "
                                f"floor (pointer entries are exempt)"))


def _valid_date(y, m, d) -> bool:
    try:
        date(int(y), int(m), int(d))
        return True
    except ValueError:
        return False


def check_naming(entry: Entry, vault: Vault, findings: list) -> None:
    rel, slug = entry.rel, entry.slug
    if not SLUG_RE.match(slug):
        findings.append(Finding(rel, 0, "ERROR",
                                f"N01: filename '{slug}' is not a kebab-case slug"))
        return
    if entry.category in ("project", "device") and "on" in slug.split("-"):
        findings.append(Finding(rel, 0, "ERROR",
                                "N02: project/device slugs must not contain the token 'on' "
                                "(reserved for recipe grammar)"))
    if entry.category == "recipe":
        if not slug.startswith("install-") or "-on-" not in slug:
            findings.append(Finding(rel, 0, "ERROR",
                                    "N03: recipe filename must be install-<project>-on-<device>"))
            return
        left, right = slug[len("install-"):].rsplit("-on-", 1)  # LAST '-on-' wins
        left_entry = vault.slug_index.get(left)
        right_entry = vault.slug_index.get(right)
        if left_entry is None or left_entry.category != "project":
            findings.append(Finding(rel, 0, "ERROR",
                                    f"N03: recipe project segment '{left}' does not resolve "
                                    f"to a project entry"))
        if right_entry is None or right_entry.category != "device":
            findings.append(Finding(rel, 0, "ERROR",
                                    f"N03: recipe device segment '{right}' does not resolve "
                                    f"to a device entry"))
        deps = entry.relations.get("depends_on", [])
        runs = entry.relations.get("runs_on", [])
        if left not in deps:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"N04: recipe must carry depends_on: [[{left}]]"))
        if right not in runs:
            findings.append(Finding(rel, 0, "ERROR",
                                    f"N04: recipe must carry runs_on: [[{right}]]"))
        for seg, target in ((left, left_entry), (right, right_entry)):
            if target is not None and target.status != "proven":
                findings.append(Finding(rel, 0, "WARN",
                                        f"N05: recipe target '{seg}' is not status proven"))


# ---------------------------------------------------------------------------
# Relations graph (R01–R06) and staleness (S01–S02)
# ---------------------------------------------------------------------------

def check_relations_graph(vault: Vault, findings: list) -> None:
    for entry in vault.entries:
        for pred, targets in entry.relations.items():
            if pred not in ALL_PREDICATES:
                findings.append(Finding(entry.rel, 0, "ERROR",
                                        f"R01: predicate '{pred}' not in _meta/predicates.md"))
                continue
            for slug in targets:
                if slug == entry.slug:
                    findings.append(Finding(entry.rel, 0, "ERROR",
                                            f"R03: self-edge '{pred}' to own slug"))
                    continue
                target = vault.slug_index.get(slug)
                if target is None:
                    findings.append(Finding(entry.rel, 0, "ERROR",
                                            f"R02: dangling relations target [[{slug}]] — "
                                            f"edges never dangle (planned.md excuses prose "
                                            f"links only)"))
                    continue
                if target.status == "hold":
                    findings.append(Finding(entry.rel, 0, "ERROR",
                                            f"R05: edge to hold entry [[{slug}]] — hold is "
                                            f"forbidden for new nodes"))
                if pred in SYMMETRIC:
                    continue  # one direction satisfies both (predicates.md)
                inverse = INVERSE.get(pred)
                if inverse and entry.slug not in target.relations.get(inverse, []):
                    findings.append(Finding(entry.rel, 0, "WARN",
                                            f"R06: missing inverse — [[{slug}]] should carry "
                                            f"'{inverse}: [[{entry.slug}]]'"))

    # R04 — supersedes cycles (iterative DFS over the supersedes subgraph).
    sup_edges = {e.slug: [s for s in e.relations.get("supersedes", [])
                          if s in vault.slug_index]
                 for e in vault.entries}
    for start in sup_edges:
        stack, seen = [(start, ())], set()
        while stack:
            node, chain = stack.pop()
            for nxt in sup_edges.get(node, []):
                if nxt == start:
                    findings.append(Finding(vault.slug_index[start].rel, 0, "ERROR",
                                            f"R04: supersedes cycle "
                                            f"{' -> '.join(chain + (start, nxt))}"))
                elif nxt not in seen:
                    seen.add(nxt)
                    stack.append((nxt, chain + (start,)))


def check_staleness(entry: Entry, today: date, findings: list) -> None:
    if entry.last_verified is None:
        return
    age = (today - entry.last_verified).days
    if age > STALE_ERROR_DAYS and entry.status == "proven":
        findings.append(Finding(entry.rel, 0, "ERROR",
                                f"S02: proven entry last_verified {age}d ago (>180d) — "
                                f"lint proposes demotion (a human applies it)"))
    elif age > STALE_WARN_DAYS:
        findings.append(Finding(entry.rel, 0, "WARN",
                                f"S01: last_verified {age}d ago (>90d) — re-verify"))


# ---------------------------------------------------------------------------
# Index generation (§Index contract; schema.md X01/X02)
# ---------------------------------------------------------------------------

def index_line(entry: Entry, from_folder: str | None) -> str:
    relpath = f"{entry.slug}.md" if from_folder == entry.folder else f"{entry.folder}/{entry.slug}.md"
    tags = ",".join(sorted(entry.tags)[:3])
    return f"- [{entry.title}]({relpath}): {entry.summary} | {entry.status} | {tags}"


def render_root_index(vault: Vault, header: str | None) -> str:
    by_cat = {c: [] for c in FOLDER_CATEGORY.values()}
    for e in vault.entries:
        if e.category:
            by_cat[e.category].append(e)
    counts = {s: sum(1 for e in vault.entries if e.status == s)
              for s in ("proven", "testing", "candidate")}
    tally = f"{counts['proven']} proven · {counts['testing']} testing · {counts['candidate']} candidate"
    if counts["proven"] == 0:
        tally += f" — {TALLY_OVERRIDE}"
    parts = [MARKER, ""]
    if header:
        parts += [header, ""]
    parts += [tally, ""]
    for folder, category in FOLDER_CATEGORY.items():
        proven = sorted((e for e in by_cat[category] if e.status == "proven"),
                        key=lambda e: e.slug.encode())
        if proven:  # empty proven sections are omitted
            parts += [f"## {folder.capitalize()}", ""]
            parts += [index_line(e, None) for e in proven]
            parts.append("")
    optional = sorted((e for e in vault.entries if e.status in ("candidate", "testing")),
                      key=lambda e: e.slug.encode())
    parts += ["## Optional", ""]
    parts += [index_line(e, None) for e in optional]
    return "\n".join(parts).rstrip("\n") + "\n"


def render_category_index(vault: Vault, folder: str) -> str:
    category = FOLDER_CATEGORY[folder]
    entries = sorted((e for e in vault.entries if e.category == category),
                     key=lambda e: e.slug.encode())
    proven = [e for e in entries if e.status == "proven"]
    optional = [e for e in entries if e.status in ("candidate", "testing", "hold")]
    parts = [MARKER, "", f"# {folder.capitalize()}", ""]
    if proven:
        parts += ["## Proven", ""] + [index_line(e, folder) for e in proven] + [""]
    parts += ["## Optional", ""] + [index_line(e, folder) for e in optional]
    return "\n".join(parts).rstrip("\n") + "\n"


def expected_indexes(vault: Vault, header: str | None) -> dict:
    """path (vault-relative) -> content for every generated index."""
    out = {"llms.txt": render_root_index(vault, header)}
    for folder in FOLDER_CATEGORY:
        if (vault.root / folder).is_dir():
            out[f"{folder}/llms.txt"] = render_category_index(vault, folder)
    return out


def check_generated_files(vault: Vault, header: str | None, check_mode: bool,
                          write: bool, findings: list) -> None:
    expected = expected_indexes(vault, header)
    for rel, content in expected.items():
        path = vault.root / rel
        if path.exists():
            existing = path.read_text(encoding="utf-8")
            if MARKER not in existing.split("\n")[:3]:
                findings.append(Finding(rel, 1, "ERROR",
                                        "X01: generated file missing the do-not-hand-edit "
                                        "marker"))
            if existing != content:
                findings.append(Finding(rel, 0, "ERROR" if check_mode else "WARN",
                                        "X02: generated index is stale (run build.py)"))
        elif check_mode:
            findings.append(Finding(rel, 0, "ERROR", "X02: generated index missing"))
        if write:
            path.write_text(content, encoding="utf-8")
        # B09 budgets apply to generated indexes too (warning-only).
        tokens = TOKEN(len(content))
        if rel == "llms.txt":
            n_lines = content.count("\n")
            if tokens > ROOT_INDEX_TOKEN_CEILING or n_lines > ROOT_INDEX_LINE_CEILING:
                findings.append(Finding(rel, 0, "WARN",
                                        f"B09: root index ~{int(tokens)} tokens / {n_lines} "
                                        f"lines (caps {ROOT_INDEX_TOKEN_CEILING}/{ROOT_INDEX_LINE_CEILING})"))
        elif tokens > CATEGORY_INDEX_TOKEN_CEILING:
            findings.append(Finding(rel, 0, "WARN",
                                    f"B09: category index ~{int(tokens)} tokens exceeds "
                                    f"{CATEGORY_INDEX_TOKEN_CEILING}"))


