#!/usr/bin/env python3
"""build.py — validator + index generator for the knowledge vault.

Spec: knowledge/README.md (spec v2, LOCKED 2026-10-12). Sections referenced
below use the spec's own vocabulary: §Frontmatter, §Relations, §Status
lifecycle, §Index contract, §Content trust, §Tooling.

Python >= 3.11 per spec. Dependency: PyYAML only.

Usage:
    python3 _meta/build.py            validate vault + regenerate all llms.txt in place
    python3 _meta/build.py --check    validate + fail if regeneration would diff (writes nothing)
    python3 _meta/build.py --selftest run the golden-fixture suite and nothing else

Exit code is non-zero when any ERROR-level finding exists (or --check sees a
diff, or --selftest fails). All findings print grouped by file.
"""

